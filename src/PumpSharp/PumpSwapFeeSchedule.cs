using PumpSharp.Chain;

namespace PumpSharp;

/// <summary>One market-cap tier of a PumpSwap fee schedule.</summary>
public readonly record struct PumpSwapFeeTier
{
    /// <summary>
    /// The market cap at or above which this tier applies, in quote units.
    ///
    /// A <c>u128</c> in the IDL and kept as one here. Narrowing it to
    /// <c>u64</c> would select the wrong tier for a pool above the narrowed
    /// bound.
    /// </summary>
    public required UInt128 MarketCapThreshold { get; init; }

    /// <summary>The rates this tier charges.</summary>
    public required PumpSwapFees Fees { get; init; }
}

/// <summary>
/// The PumpSwap <c>FeeConfig</c> account: every schedule a pool might pay.
/// </summary>
public sealed record PumpSwapFeeConfig
{
    /// <summary>PDA bump.</summary>
    public required byte Bump { get; init; }

    /// <summary>The config's admin.</summary>
    public required Pubkey Admin { get; init; }

    /// <summary>What a pool that is not a canonical pump pool pays, and the fallback for an unset exotic schedule.</summary>
    public required PumpSwapFees FlatFees { get; init; }

    /// <summary>Market-cap tiers for a canonical pump pool quoted in something SOL-like.</summary>
    public required IReadOnlyList<PumpSwapFeeTier> FeeTiers { get; init; }

    /// <summary>Market-cap tiers for a canonical pump pool quoted in a listed stable. Empty on accounts written before the field existed.</summary>
    public required IReadOnlyList<PumpSwapFeeTier> StableFeeTiers { get; init; }

    /// <summary>
    /// Flat fees for a canonical pump pool quoted in neither.
    ///
    /// All zeroes means unset, not free. The program then falls back to
    /// <see cref="FlatFees"/>. Reading all zeroes as "no fees" would price every
    /// exotic pool at cost.
    /// </summary>
    public required PumpSwapFees ExoticFlatFees { get; init; }

    /// <summary>Whether the exotic schedule has been set at all.</summary>
    public bool ExoticFeesSet =>
        ExoticFlatFees.LpFeeBps != 0
        || ExoticFlatFees.ProtocolFeeBps != 0
        || ExoticFlatFees.CreatorFeeBps != 0;
}

/// <summary>Which schedule a pool's quote mint selects.</summary>
public enum PumpSwapQuoteSchedule
{
    /// <summary>Not determined.</summary>
    Unknown = 0,

    /// <summary>SOL, wrapped SOL or the Token-2022 native mint: the tiered schedule.</summary>
    SolLike = 1,

    /// <summary>A listed stable: the stable tiers.</summary>
    Stable = 2,

    /// <summary>Anything else: the exotic flat fees, falling back to flat.</summary>
    Exotic = 3,
}

/// <summary>Why a fee schedule could not be resolved.</summary>
public enum PumpSwapFeeScheduleRefusal
{
    /// <summary>Resolved.</summary>
    None = 0,

    /// <summary>A reserve or the supply is zero, so there is no market cap to tier on.</summary>
    NoMarketCap = 1,

    /// <summary>The selected tier list is empty, so there is no schedule to choose from.</summary>
    NoTiers = 2,

    /// <summary>The quote mint's schedule was not stated.</summary>
    UnknownSchedule = 3,

    /// <summary>
    /// No longer returned: mayhem pools are now priced on the program's fixed
    /// supply. The value stays reserved so stored results keep their meaning.
    /// </summary>
    MayhemPool = 4,

}

/// <summary>
/// Resolves the rates a PumpSwap pool charges.
///
/// Checked against a 336-case grid generated by running <c>computeFeesBps</c>
/// from <c>@pump-fun/pump-swap-sdk</c> 2.2.0, plus 864 cases covering
/// mayhem, actual versus fixed supply, creator overrides and the legacy
/// stable-tier fallback.
///
/// The vectors established these rules, none of which are in the IDL:
///
/// <list type="bullet">
/// <item>Tiers apply only to a canonical pump pool. The SDK decides that
/// from the pool's creator (<c>isPumpPool(baseMint, poolCreator)</c>
/// compares it with <c>pumpPoolAuthorityPda(baseMint)</c>). Any other pool
/// pays <c>flatFees</c>, whatever its quote mint or market cap.</item>
/// <item>The market cap is <c>baseSupply × quoteReserve ÷ baseReserve</c>,
/// and the tier is the highest one whose threshold the cap reaches. The
/// threshold is inclusive.</item>
/// <item>An all-zero exotic schedule means unset, and the program charges
/// <c>flatFees</c> instead.</item>
/// <item>A per-pool creator rate replaces the schedule's creator rate while
/// <c>creatorFeeConfigurable</c> is on and the pool's rate is non-zero. The
/// LP and protocol rates still come from the schedule.</item>
/// </list>
///
/// Unknown schedules, empty tier lists after the legacy fallback and missing
/// market-cap inputs are refused. Mayhem pools use the program's fixed
/// supply, not the live supply.
/// </summary>
public static class PumpSwapFeeSchedule
{
    /// <summary>The program's TOTAL_TOKEN_SUPPLY, used for the market cap of mayhem pools.</summary>
    public const ulong MayhemSupplyUnits = 1_000_000_000_000_000;
    /// <summary>
    /// The market cap a tier is selected on: <c>baseSupply × quoteReserve ÷
    /// baseReserve</c>, in quote units.
    ///
    /// Returned as <see cref="UInt128"/> because a supply times a reserve
    /// overflows <see cref="ulong"/>.
    /// </summary>
    public static bool TryMarketCap(
        ulong baseSupplyUnits,
        ulong baseReserveUnits,
        ulong quoteReserveUnits,
        out UInt128 marketCap)
    {
        marketCap = default;

        if (baseReserveUnits == 0 || baseSupplyUnits == 0 || quoteReserveUnits == 0)
        {
            return false;
        }

        marketCap = (UInt128)baseSupplyUnits * quoteReserveUnits / baseReserveUnits;
        return true;
    }

    /// <summary>Which schedule a quote mint selects.</summary>
    public static PumpSwapQuoteSchedule ScheduleFor(Pubkey quoteMint) =>
        PumpQuoteMints.IsSolLike(quoteMint) ? PumpSwapQuoteSchedule.SolLike
        : PumpQuoteMints.IsStable(quoteMint) ? PumpSwapQuoteSchedule.Stable
        : PumpSwapQuoteSchedule.Exotic;

    /// <summary>
    /// Resolves the rates a trade on this pool pays.
    /// </summary>
    /// <param name="config">The decoded <c>FeeConfig</c> account.</param>
    /// <param name="schedule">Which schedule the pool's quote mint selects.</param>
    /// <param name="isCanonicalPumpPool">
    /// Whether the pool's creator is <c>pumpPoolAuthorityPda(baseMint)</c>.
    /// The caller states it (see <see cref="PumpAddresses.TryPoolAuthority"/>)
    /// because a wrong guess here would move the pool onto the wrong schedule.
    /// </param>
    /// <param name="baseSupplyUnits">The base mint's total supply.</param>
    /// <param name="baseReserveUnits">The pool's base reserve.</param>
    /// <param name="quoteReserveUnits">The pool's quote reserve.</param>
    /// <param name="isMayhemMode">Uses the program's fixed supply when true.</param>
    /// <param name="poolCreatorFeeBps">The pool's own creator rate, or zero when not configured.</param>
    /// <param name="creatorFeeConfigurable">The global switch for per-pool creator rates.</param>
    /// <param name="hasCoinCreator">Whether the pool has a coin creator. Without one, no creator rate applies.</param>
    /// <param name="fees">The resolved rates.</param>
    /// <param name="refusal">Why the rates could not be resolved.</param>
    public static bool TryResolve(
        PumpSwapFeeConfig config,
        PumpSwapQuoteSchedule schedule,
        bool isCanonicalPumpPool,
        ulong baseSupplyUnits,
        ulong baseReserveUnits,
        ulong quoteReserveUnits,
        bool isMayhemMode,
        ulong poolCreatorFeeBps,
        bool creatorFeeConfigurable,
        bool hasCoinCreator,
        out PumpSwapFees fees,
        out PumpSwapFeeScheduleRefusal refusal)
    {
        ArgumentNullException.ThrowIfNull(config);

        fees = default;

        if (schedule is not (PumpSwapQuoteSchedule.SolLike or PumpSwapQuoteSchedule.Stable or PumpSwapQuoteSchedule.Exotic))
        {
            refusal = PumpSwapFeeScheduleRefusal.UnknownSchedule;
            return false;
        }

        refusal = PumpSwapFeeScheduleRefusal.None;

        // A pool not created by the canonical authority pays the flat schedule,
        // whatever its quote mint and market cap.
        if (!isCanonicalPumpPool)
        {
            fees = Compose(config.FlatFees, poolCreatorFeeBps, creatorFeeConfigurable, hasCoinCreator);
            return true;
        }

        if (schedule is PumpSwapQuoteSchedule.Exotic)
        {
            var exotic = config.ExoticFeesSet ? config.ExoticFlatFees : config.FlatFees;
            fees = Compose(exotic, poolCreatorFeeBps, creatorFeeConfigurable, hasCoinCreator);
            return true;
        }

        var tiers = schedule is PumpSwapQuoteSchedule.Stable && config.StableFeeTiers.Count != 0
            ? config.StableFeeTiers
            : config.FeeTiers;

        if (tiers.Count == 0)
        {
            refusal = PumpSwapFeeScheduleRefusal.NoTiers;
            return false;
        }

        if (!TryMarketCap(isMayhemMode ? MayhemSupplyUnits : baseSupplyUnits,
            baseReserveUnits, quoteReserveUnits, out var marketCap))
        {
            refusal = PumpSwapFeeScheduleRefusal.NoMarketCap;
            return false;
        }

        // The highest tier the cap reaches, inclusive at the threshold.
        var chosen = tiers[0];
        foreach (var tier in tiers)
        {
            if (marketCap >= tier.MarketCapThreshold)
            {
                chosen = tier;
            }
        }

        fees = Compose(chosen.Fees, poolCreatorFeeBps, creatorFeeConfigurable, hasCoinCreator);
        return true;
    }

    /// <summary>
    /// Applies the per-pool creator override to a schedule's rates.
    ///
    /// Only the creator rate changes; the LP and protocol rates always come
    /// from the schedule. The override applies only while the global switch is
    /// on and the pool's rate is non-zero, because zero means "not configured",
    /// not "free".
    /// </summary>
    private static PumpSwapFees Compose(
        in PumpSwapFees schedule,
        ulong poolCreatorFeeBps,
        bool creatorFeeConfigurable,
        bool hasCoinCreator) => new()
        {
            LpFeeBps = schedule.LpFeeBps,
            ProtocolFeeBps = schedule.ProtocolFeeBps,
            CreatorFeeBps = creatorFeeConfigurable && poolCreatorFeeBps != 0
                ? poolCreatorFeeBps
                : schedule.CreatorFeeBps,
            HasCoinCreator = hasCoinCreator,
        };
}

/// <summary>
/// The quote mints that select each fee schedule, copied from the SDK's
/// exported constants. Changing either set needs a program upgrade.
/// </summary>
public static class PumpQuoteMints
{
    /// <summary>Wrapped SOL.</summary>
    public const string WrappedSol = "So11111111111111111111111111111111111111112";

    /// <summary>The Token-2022 native mint.</summary>
    public const string NativeMint2022 = "9pan9bMn5HatX4EJdBwg9VgCa7Uz5HL8N1m5D3NdXejP";

    /// <summary>USDC, the one listed stable.</summary>
    public const string Usdc = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v";

    /// <summary>
    /// Whether a quote mint selects the tiered SOL schedule.
    ///
    /// The all-zero key counts as SOL. Legacy bonding curves store it for SOL,
    /// and the fee program's <c>is_sol_like_quote_mint</c> treats it the same
    /// way. Without this, every legacy curve's pool would land on the exotic
    /// schedule.
    /// </summary>
    public static bool IsSolLike(Pubkey quoteMint) =>
        quoteMint.IsDefault
        || Matches(quoteMint, WrappedSol)
        || Matches(quoteMint, NativeMint2022);

    /// <summary>Whether a quote mint selects the stable tiers.</summary>
    public static bool IsStable(Pubkey quoteMint) => Matches(quoteMint, Usdc);

    private static bool Matches(Pubkey quoteMint, string base58) =>
        Pubkey.TryParse(base58, out var known) && quoteMint == known;
}
